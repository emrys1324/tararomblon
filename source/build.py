import os, shutil, re
LIVEHEAD='<link rel="icon" href="/api/icon"><link rel="apple-touch-icon" href="/api/icon"><link rel="manifest" href="/manifest.webmanifest"><meta name="apple-mobile-web-app-capable" content="yes"><meta name="mobile-web-app-capable" content="yes"><meta name="apple-mobile-web-app-title" content="Tara Romblon">'
B=os.path.dirname(os.path.abspath(__file__))+'/'
d=B+'src/'; srv=B+'server/'; o=B+'out/'
for x in ('preview','vercel','supabase'): shutil.rmtree(o+x, ignore_errors=True)
R=lambda f:open(d+f).read()
css=R('style.css');pricing=R('pricing.js');rules=R('rules.js');core=R('core.js')
common=R('common_head.js')+'\n'+R('common_api.js')+'\n'+R('common_ui.js')
APIDEMO="  apiUrl: '',"; APILIVE="  apiUrl: '/api',"
assert APIDEMO in common
PAGES=[('template.html',R('app_body.js'),'index.html','',''),
       ('portal_template.html',R('admin_catalog.js')+'\n'+R('admin.js'),'admin.html','Tara Romblon — Super Admin','SUPER ADMIN'),
       ('portal_template.html',R('merchant.js'),'merchant.html','Tara Romblon — Merchant','MERCHANT'),
       ('portal_template.html',R('rider.js'),'rider.html','Tara Romblon — Rider','RIDER')]
def page(tpl,app,title,role,live):
    c=common.replace(APIDEMO,APILIVE) if live else common
    t0=R(tpl)
    if live: t0=re.sub(r'<link rel="icon"[^>]*>', LIVEHEAD if tpl=='template.html' else LIVEHEAD.replace('/manifest.webmanifest','/api/manifest?app='+{'SUPER ADMIN':'admin','MERCHANT':'merchant','RIDER':'rider'}[role]).replace('content="Tara Romblon"','content="TR '+{'SUPER ADMIN':'Admin','MERCHANT':'Merchant','RIDER':'Rider'}[role]+'"'), t0, count=1)
    return t0.replace('/*CSS*/',css).replace('/*PRICING*/',pricing).replace('/*RULES*/',rules).replace('/*CORE*/',core).replace('/*APP*/',c+'\n'+app).replace('/*TITLE*/',title).replace('/*ROLE*/',role)
for folder,live in (('preview',False),('vercel',True)):
    os.makedirs(o+folder,exist_ok=True)
    for tpl,app,out,title,role in PAGES:
        t=page(tpl,app,title,role,live); open(o+folder+'/'+out,'w').write(t); print(folder,out,len(t))
# Vercel project: static pages + api functions + config
V=o+'vercel/'
shutil.copytree(srv+'api',V+'api')
for f in ('vercel.json','package.json','.env.example'): shutil.copy(srv+f,V+f)
for f in os.listdir(srv+'static'): shutil.copy(srv+'static/'+f,V+f)
open(V+'api/_lib/shared.js','w').write('/* GENERATED by build.py from src/pricing.js, src/rules.js, src/core.js. Edit those, not this. */\n'+pricing+'\n'+rules+'\n'+core+'\nmodule.exports = { createCore, Pricing, Rules, DEFAULT_SETTINGS };\n')
os.makedirs(o+'supabase',exist_ok=True); shutil.copy(srv+'supabase/schema.sql',o+'supabase/schema.sql')
print('ok')
