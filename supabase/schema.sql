-- Business applications, rider applications, payout statements and the reward points ledger are included.
-- Every record is stored whole in a JSONB "data" column, so the apps can add fields
-- without database changes. Only the Vercel API (service role key) can read or write:
-- Row Level Security is ON with no policies, which blocks the public anon key completely.

create table if not exists public.customers    (id text primary key, data jsonb not null, seq bigint generated by default as identity, created_at timestamptz not null default now(), updated_at timestamptz not null default now());
create table if not exists public.staff        (id text primary key, data jsonb not null, seq bigint generated by default as identity, created_at timestamptz not null default now(), updated_at timestamptz not null default now());
create table if not exists public.bookings     (id text primary key, data jsonb not null, seq bigint generated by default as identity, created_at timestamptz not null default now(), updated_at timestamptz not null default now());
create table if not exists public.threads      (id text primary key, data jsonb not null, seq bigint generated by default as identity, created_at timestamptz not null default now(), updated_at timestamptz not null default now());
create table if not exists public.messages     (id text primary key, data jsonb not null, seq bigint generated by default as identity, created_at timestamptz not null default now(), updated_at timestamptz not null default now());
create table if not exists public.events       (id text primary key, data jsonb not null, seq bigint generated by default as identity, created_at timestamptz not null default now(), updated_at timestamptz not null default now());
create table if not exists public.applications (id text primary key, data jsonb not null, seq bigint generated by default as identity, created_at timestamptz not null default now(), updated_at timestamptz not null default now());
create table if not exists public.payouts      (id text primary key, data jsonb not null, seq bigint generated by default as identity, created_at timestamptz not null default now(), updated_at timestamptz not null default now());
create table if not exists public.points       (id text primary key, data jsonb not null, seq bigint generated by default as identity, created_at timestamptz not null default now(), updated_at timestamptz not null default now());

-- Settings and listings (key 'catalog')
create table if not exists public.kv    (key text primary key, value jsonb, updated_at timestamptz not null default now());
-- Short-lived values: sign-in codes, rate limits
create table if not exists public.cache (key text primary key, value text, expires_at timestamptz not null);

-- Fast look-ups
create index if not exists customers_tokens_idx on public.customers using gin ((data->'tokens'));
create index if not exists staff_tokens_idx     on public.staff     using gin ((data->'tokens'));
create index if not exists bookings_seq_idx     on public.bookings (seq);
create index if not exists messages_seq_idx     on public.messages (seq);
create index if not exists events_seq_idx       on public.events (seq);
create index if not exists cache_expires_idx    on public.cache (expires_at);

-- Lock every table to the server
alter table public.customers    enable row level security;
alter table public.staff        enable row level security;
alter table public.bookings     enable row level security;
alter table public.threads      enable row level security;
alter table public.messages     enable row level security;
alter table public.events       enable row level security;
alter table public.applications enable row level security;
alter table public.payouts      enable row level security;
alter table public.points       enable row level security;
alter table public.kv           enable row level security;
alter table public.cache        enable row level security;

-- File storage: listing photos are public; IDs and payment proofs are private (shown through 10-minute signed links)
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('photos',  'photos',  true,  5242880, array['image/jpeg','image/png','image/webp','image/gif']),
       ('uploads', 'uploads', false, 5242880, array['image/jpeg','image/png','image/webp','image/gif'])
on conflict (id) do update set public = excluded.public, file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;
